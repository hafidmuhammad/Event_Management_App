/**
 * Generates the colour-token blocks of src/app/globals.css from
 * src/lib/theme/presets.ts.
 *
 *   pnpm theme:css           rewrite the generated region
 *   pnpm theme:css --check   exit 1 if the file is out of date (writes nothing)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { colorTokens, sizeTokens, themePresets, type ThemePreset } from "../src/lib/theme/presets";

const START = "/* theme-presets:start */";
const END = "/* theme-presets:end */";
const file = join(process.cwd(), "src", "app", "globals.css");

function declarations(preset: ThemePreset) {
  const lines = [`  color-scheme: ${preset.mode};`];
  for (const name of colorTokens) {
    const value = preset.tokens[name];
    if (!value) throw new Error(`Preset "${preset.id}" is missing the colour token "${name}".`);
    lines.push(`  --${name}: ${value};`);
  }
  for (const name of sizeTokens) {
    const value = preset.tokens[name];
    if (value) lines.push(`  --${name}: ${value};`);
  }
  return lines.join("\n");
}

/**
 * `dark` and `light` keep their historical selectors. Every other preset is
 * matched on <html> with extra specificity so it beats `:root`, and on any
 * element so a subtree (a presentation screen) can opt in.
 */
function selector(preset: ThemePreset) {
  if (preset.id === "dark") return ':root,\n[data-theme="dark"]';
  if (preset.id === "light") return '[data-theme="light"]';
  return `html[data-theme="${preset.id}"],\n[data-theme="${preset.id}"]`;
}

function generate() {
  const blocks = themePresets.map((preset) => `/* ${preset.id}: ${preset.description} */\n${selector(preset)} {\n${declarations(preset)}\n}`);
  // ::backdrop does not reliably inherit custom properties, so each theme states its own scrim literally.
  const scrims = themePresets
    .filter((preset) => preset.scope === "app")
    .map((preset) => `html[data-theme="${preset.id}"] .app-dialog::backdrop { background: ${preset.tokens.backdrop}; }`);
  return [
    START,
    "/* GENERATED by scripts/generate-theme-css.ts from src/lib/theme/presets.ts. Do not edit by hand. */",
    "",
    blocks.join("\n\n"),
    "",
    "/* Dialog scrim per theme. */",
    scrims.join("\n"),
    END,
  ].join("\n");
}

const current = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
const from = current.indexOf(START);
const to = current.indexOf(END);
if (from < 0 || to < 0 || to < from) {
  console.error(`Markers ${START} ... ${END} not found in src/app/globals.css.`);
  process.exit(2);
}
const next = current.slice(0, from) + generate() + current.slice(to + END.length);

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("src/app/globals.css is out of date with src/lib/theme/presets.ts. Run: pnpm theme:css");
    process.exit(1);
  }
  console.log(`Theme CSS is in sync (${themePresets.length} presets).`);
} else if (next === current) {
  console.log(`Theme CSS already up to date (${themePresets.length} presets).`);
} else {
  writeFileSync(file, next, "utf8");
  console.log(`Wrote ${themePresets.length} presets to src/app/globals.css.`);
}
